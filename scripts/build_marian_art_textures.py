#!/usr/bin/env python3
"""Marian door reliefs, inner-window M lunette and outer-wall rose window.

Owner, 8 November 2026: the church supplied three concept pictures (nine relief
lunettes over the nine outside doors, a silver M monogram lunette over the inner
windows, and a 60 cm stained-glass M rose). The owner chose to use them as model
textures under PUBLICATION HOLD (docs/open-source/publication-checklist.md, H8).

Two steps:

  --crop SHEET MONOGRAM ROSE   Crop the eleven textures out of the church's
                               pictures (needs Pillow). Pixel crops only: no
                               resize, colour change or retouching; JPEG is
                               re-encoded at quality 92. The supplied pictures
                               themselves are not committed.
  (default)                    Package the committed crops as same-origin data
                               URLs for offline file: viewing (stdlib only),
                               checking each file against provenance.json.
  --check                      Verify the package is current without writing.
"""
import argparse
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / "Thach_Bi_Viewer/references/11-marian-art"
OUTPUT = ROOT / "Thach_Bi_Viewer/marian-art-textures.js"
PREFIX = "references/11-marian-art/"

# Pixel boxes (left, top, right, bottom; right/bottom exclusive) in the supplied
# pictures, found from the brown frame mask of each lunette (8 Nov 2026).
SHEET_COLUMNS = [(18, 408), (445, 836), (875, 1263)]
SHEET_ROWS = [(139, 311), (361, 539), (587, 767)]
SCENES = [
    ("relief-1-annunciation", "Truyền Tin · The Annunciation (Lc 1,26-38)"),
    ("relief-2-visitation", "Mẹ Thăm Viếng · The Visitation (Lc 1,39-56)"),
    ("relief-3-nativity", "Giáng Sinh · The Nativity (Lc 2,1-20)"),
    ("relief-4-presentation", "Dâng Chúa trong Đền Thờ · The Presentation (Lc 2,22-35)"),
    ("relief-5-cana", "Tiệc Cưới Cana · The Wedding at Cana (Ga 2,1-11)"),
    ("relief-6-cross", "Mẹ dưới chân Thập Giá · Mary at the foot of the Cross (Ga 19,25-27)"),
    ("relief-7-pentecost", "Mẹ giữa Hội Thánh sơ khai · Mary with the early Church (Cv 1,12-14)"),
    ("relief-8-woman-clothed-with-the-sun", "Mẹ được rước về trời · The woman clothed with the sun (Kh 12,1)"),
    ("relief-9-assumption", "Đức Mẹ Hồn Xác Lên Trời · The Assumption (Kh 12,1-2)"),
]
MONOGRAM_BOX = (10, 16, 1270, 600)
ROSE_BOX = (63, 213, 543, 693)  # circle centre (303, 453), radius about 239 px


def crop(sheet, monogram, rose):
    from PIL import Image  # only the crop step needs Pillow
    FOLDER.mkdir(parents=True, exist_ok=True)
    jobs = []
    with Image.open(sheet) as image:
        image = image.convert("RGB")
        for index, (name, _) in enumerate(SCENES):
            (x0, x1), (y0, y1) = SHEET_COLUMNS[index % 3], SHEET_ROWS[index // 3]
            jobs.append((name, image.crop((x0, y0, x1, y1)), Path(sheet).name, (x0, y0, x1, y1)))
    with Image.open(monogram) as image:
        jobs.append(("inner-window-m-lunette", image.convert("RGB").crop(MONOGRAM_BOX), Path(monogram).name, MONOGRAM_BOX))
    with Image.open(rose) as image:
        jobs.append(("rose-window-m", image.convert("RGB").crop(ROSE_BOX), Path(rose).name, ROSE_BOX))
    for name, picture, source, box in jobs:
        out = FOLDER / f"{name}.jpg"
        picture.save(out, "JPEG", quality=92, optimize=True, progressive=False)
        print(f"{out.relative_to(ROOT)} {picture.size[0]}x{picture.size[1]} from {source} {box}")


def packaged_source():
    provenance = json.loads((FOLDER / "provenance.json").read_text())
    textures = {}
    for asset in provenance["assets"]:
        filename = asset["file"]
        if Path(filename).name != filename:
            raise ValueError("Artwork file must belong to its provenance folder")
        data = (FOLDER / filename).read_bytes()
        if hashlib.sha256(data).hexdigest() != asset["sha256"]:
            raise ValueError("Bytes differ from recorded provenance: " + filename)
        textures[PREFIX + filename] = {
            "sha256": asset["sha256"], "width": asset["width"], "height": asset["height"],
            "imageUrl": "data:image/jpeg;base64," + base64.b64encode(data).decode("ascii"),
        }
    return ("/* Generated by scripts/build_marian_art_textures.py from\n"
            " * Thach_Bi_Viewer/references/11-marian-art (church-supplied concept\n"
            " * pictures, PUBLICATION HOLD H8). Same-origin data URLs keep offline\n"
            " * file: WebGL uploads working. */\n"
            "window.CHURCH_MARIAN_ART_TEXTURES = "
            + json.dumps(textures, ensure_ascii=True, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--crop", nargs=3, metavar=("SHEET", "MONOGRAM", "ROSE"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.crop:
        crop(*args.crop)
    else:
        source = packaged_source()
        if args.check:
            if OUTPUT.read_text() != source:
                raise SystemExit("STALE Marian art texture package; rebuild it")
            print("PASS provenance hashes and deterministic Marian art texture package")
        else:
            OUTPUT.write_text(source)
            print(f"Packaged {source.count('data:image/jpeg')} Marian art textures")
