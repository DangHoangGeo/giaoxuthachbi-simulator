#!/usr/bin/env node
// Writes the saved-layout table for the parish priest's decisions of 25 October 2026 into
// Thach_Bi_Viewer/simulator/design.js (between the BEGIN/END parish-meeting markers).
//
// The table lists, for every recommended item whose place, aim, mount, circuit, type or output
// changed since the base commit, its values at the base commit (`parishMeetingBefore`), and the
// IDs that are new (`parishMeetingAdded`). `upgradeParishMeeting` in design.js moves only items
// still at those base values, removes retired ones only if untouched, and adds the new IDs once.
//
// Usage, after `node scripts/verify_simulator.cjs --electrical --export-electrical`:
//   node scripts/build_parish_migration.mjs [--check]
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASE = '015f9a8'; // last commit before the meeting work (24 Oct 2026)
const layoutPath = 'docs/electrical-grid/equipment-layout.json';
const designPath = path.join(root, 'Thach_Bi_Viewer/simulator/design.js');
const before = JSON.parse(execFileSync('git', ['show', `${BASE}:${layoutPath}`], { cwd: root, encoding: 'utf8' })).items;
const after = JSON.parse(fs.readFileSync(path.join(root, layoutPath), 'utf8')).items;

const KEYS = ['type', 'pos', 'yaw', 'tilt', 'mount', 'mountYaw', 'anchorY', 'circuit', 'lumens', 'beam', 'params', 'level', 'speed'];
const round = v => typeof v === 'number' ? Math.round(v * 1e4) / 1e4 : Array.isArray(v) ? v.map(round) : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, round(x)])) : v;
const same = (a, b) => JSON.stringify(round(a)) === JSON.stringify(round(b));
const nextById = new Map(after.map(it => [it.id, it]));
const prevIds = new Set(before.map(it => it.id));

const changed = {};
for (const it of before) {
  const next = nextById.get(it.id);
  if (next && KEYS.every(k => same(it[k], next[k]))) continue;
  changed[it.id] = Object.fromEntries(['type', 'name', 'pos', 'yaw', 'tilt', 'mount', 'circuit'].filter(k => it[k] !== undefined).map(k => [k, round(it[k])]));
}
const added = after.filter(it => !prevIds.has(it.id)).map(it => it.id);

const lines = Object.entries(changed).map(([id, v]) => `    ${JSON.stringify(id)}: ${JSON.stringify(v)},`);
const block = [
  '  // BEGIN parish-meeting table · generated by scripts/build_parish_migration.mjs from',
  `  // ${layoutPath} at ${BASE} and the current export. Do not edit by hand.`,
  '  const parishMeetingBefore = {',
  ...lines,
  '  };',
  `  const parishMeetingAdded = ${JSON.stringify(added)};`,
  '  // END parish-meeting table',
].join('\n');

const source = fs.readFileSync(designPath, 'utf8');
const re = /  \/\/ BEGIN parish-meeting table[\s\S]*?  \/\/ END parish-meeting table/;
if (!re.test(source)) throw new Error('parish-meeting markers not found in design.js');
const next = source.replace(re, block);
if (process.argv.includes('--check')) {
  if (next !== source) { console.error('design.js parish-meeting table is stale: run node scripts/build_parish_migration.mjs'); process.exit(1); }
  console.log(JSON.stringify({ parishTable: 'current', changed: Object.keys(changed).length, added: added.length }));
} else {
  fs.writeFileSync(designPath, next);
  console.log(JSON.stringify({ parishTable: 'written', changed: Object.keys(changed).length, added: added.length }));
}
